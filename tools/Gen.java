    /** The parameter lists of a method: with "N" as Tag and as String, or once when there is no "N". */
    static List<String> overloads(String params) {
        if (!params.startsWith("N ")) return List.of(params);
        return List.of("Tag" + params.substring(1), "String" + params.substring(1));
    }

    static String block(String scope) {
        StringBuilder b = new StringBuilder("    // Generated by tools/Gen.java; do not edit by hand.\n\n");
        for (String[] f : FINDS) {
            for (String params : overloads(f[1])) {
                b.append("    /** Returns ").append(f[4]).append(' ').append(scope).append(", or null. */\n");
                b.append("    public HtmlNode ").append(f[0]).append('(').append(params).append(") {\n");
                if (!f[3].isEmpty()) b.append("        if (").append(f[3]).append(") return null;\n");
                b.append("        return find(").append(f[2]).append(");\n    }\n\n");
            }
        }
        for (String[] f : FIND_ALLS) {
            for (String params : overloads(f[1])) {
                b.append("    /** Returns ").append(f[3]).append(' ').append(scope).append(". */\n");
                b.append("    public List<HtmlNode> ").append(f[0]).append('(').append(params).append(") {\n");
                b.append("        return findAll(").append(f[2]).append(");\n    }\n\n");
            }
        }
        return b.toString();
    }

    static String nodeOnly() {
        StringBuilder b = new StringBuilder();
        for (String[] f : ISS) {
            for (String params : overloads(f[1])) {
                b.append("    /** Whether ").append(f[3]).append(". */\n");
                b.append("    public boolean ").append(f[0]).append('(').append(params).append(") {\n");
                b.append("        return is(").append(f[2]).append(");\n    }\n\n");
            }
        }
        for (String[] f : NAVS) {
            for (String params : overloads(f[1])) {
                b.append("    /** Returns ").append(f[4]).append(". */\n");
                b.append("    public ").append(f[3]).append(' ').append(f[0]).append('(').append(params).append(") {\n");
                b.append("        return ").append(f[2]).append(";\n    }\n\n");
            }
        }
        for (String[] a : ATTRIBUTES) {
            b.append("    /** The decoded value of the ").append(a[2]).append(" attribute; \"\" when it is missing. */\n");
            b.append("    public String ").append(a[0]).append("() {\n");
            b.append("        return attr(Attr.").append(a[1]).append(");\n    }\n\n");
        }
        return b.toString();
    }

    static void shortcuts() throws IOException {
        replaceBlock("HtmlDocument.java", "document", block("in the document"));
        replaceBlock("HtmlNode.java", "node", block("inside the tag") + nodeOnly());
    }

    static void replaceBlock(String file, String marker, String content) throws IOException {
        Path path = OUT.resolve(file);
        String text = read(path);
        String open = "    // <shortcuts " + marker + ">\n";
        String close = "    // </shortcuts " + marker + ">";
        int a = text.indexOf(open);
        int z = text.indexOf(close);
        if (a < 0 || z < a) throw new IllegalStateException("no shortcut markers in " + file);
        String body = content.endsWith("\n\n") ? content.substring(0, content.length() - 1) : content;
        Files.writeString(path, text.substring(0, a + open.length()) + body + text.substring(z), StandardCharsets.UTF_8);
    }
