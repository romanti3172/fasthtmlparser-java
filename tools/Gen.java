// Builds Tag.java, Attr.java and Entities.java from the C# sources of z3l.FastHtmlParser, so that the Java port uses
// exactly the same tag list, attribute names and HTML5 entity table, and writes the one-call shortcuts
// (findByNameClass, isNameClass, parentByName, ...) into HtmlDocument.java and HtmlNode.java between the
// "// <shortcuts ...>" markers.
//
//   java tools/Gen.java ../z3l.FastHtmlParser/src/z3l.FastHtmlParser

